def _flat(story):
    """One sentence pair per entry, whether they were written one by one or
    collected into P() groups."""
    for ch in story.get("chapters", []):
        if "pairs" in ch:
            ch["pairs"] = [p for item in ch["pairs"]
                           for p in (item if isinstance(item, list) else [item])]
    return story




# Their own wording must survive: BBC's transcripts are quotations, and
# distinctions.json exists to contrast the two standards.
QUOTED = {"bbc_6min.json", "distinctions.json"}

# A proper noun that happens to contain a British spelling, and one data field
# whose name is part of the grammar engine's contract (nlp/fluentify-nlp.js
# returns analysedSentence, so the page has to read that exact key).
PROTECT = ["Grey's Anatomy", "Earl Grey", "Grey", "Centre Pompidou",
           "TraveLodge", "theatre royal", "analysedSentence",
           # README's own example of the pair, kept as written.
           "*petrol → gas*, *colour → color*"]

TOKEN = re.compile(r"[A-Za-z][A-Za-z'’\-]*")


def match_case(src: str, repl: str) -> str:
    if src.isupper() and len(src) > 1:
        return repl.upper()
    if src[0].isupper():
        return repl[0].upper() + repl[1:]
    return repl


def convert(text: str) -> tuple[str, int]:
    saved = {}

    def hide(m):
        token = f"\x00{len(saved)}\x00"
        saved[token] = m.group(0)
        return token

    if saved or PROTECT:
        pattern = re.compile("|".join(re.escape(p) for p in PROTECT))
        text = pattern.sub(hide, text)

    count = 0

    def one(m):
        nonlocal count
        parts = m.group(0).split("-")
        out = []
        for part in parts:
            repl = MAP.get(part.lower())
            if repl is None:
                out.append(part)
            else:
                out.append(match_case(part, repl))
                count += 1
        return "-".join(out)

    text = TOKEN.sub(one, text)
    for token, phrase in saved.items():
        text = text.replace(token, phrase)
    return text, count


# README's "English standard" section lists the British forms on purpose, as
# the mapping the app converts away from. Everything else in the file is copy.
README_START = "## English standard: American English"
README_END = "## Adding content"


def readme_parts(text: str):
    i = text.find(README_START)
    j = text.find(README_END)
    if i == -1 or j == -1 or j < i:
        return text, "", ""
    return text[:i], text[i:j], text[j:]


def targets():
    for name in CONTENT:
        p = ROOT / name
        if p.exists():
            yield p
    for p in sorted((ROOT / "tools").glob("*.py")):
        if p.name in {"audit_british.py", "americanize.py", "check_american.py"}:
            continue
        yield p
    for p in sorted(ROOT.glob("tests_*.py")):
        yield p


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    total = 0
    dirty = 0
    for path in targets():
        # chatbot.py keeps the British forms as data in BRITISH_TO_AMERICAN,
        # so converting it would rewrite its own lookup keys.
        if path.name in QUOTED or path.name == "chatbot.py":
            continue
        text = path.read_text(encoding="utf-8")
        if path.name == "README.md":
            head, block, tail = readme_parts(text)
            head, n1 = convert(head)
            tail, n2 = convert(tail)
            new, n = head + block + tail, n1 + n2
        else:
            new, n = convert(text)
        if not n:
            continue
        dirty += 1
        total += n
        print(f"{n:5d}  {path.relative_to(ROOT)}")
        if args.write:
            path.write_text(new, encoding="utf-8")
    print(f"{'converted' if args.write else 'would convert'} {total} words "
          f"in {dirty} files")
    if not args.write and total:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
